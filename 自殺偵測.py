# 3. 統計輔助函式 (Effect Size Calculations)
# ==========================================
def get_cohens_d(group1, group2):
    """計算 Cohen's d (參數型效果量)"""
    n1, n2 = len(group1), len(group2)
    v1, v2 = np.var(group1, ddof=1), np.var(group2, ddof=1)
    pooled_sd = np.sqrt(((n1 - 1) * v1 + (n2 - 1) * v2) / (n1 + n2 - 2))
    if pooled_sd == 0:
        return 0
    return (np.mean(group1) - np.mean(group2)) / pooled_sd

def get_cliffs_delta(group1, group2):
    """計算 Cliff's delta (非參數型效果量)"""
    n1, n2 = len(group1), len(group2)
    g1, g2 = np.array(group1), np.array(group2)
    diff = np.expand_dims(g1, axis=1) - np.expand_dims(g2, axis=0)
    delta = (np.sum(diff > 0) - np.sum(diff < 0)) / (n1 * n2)
    return delta

def interpret_delta(delta):
    """解讀 Cliff's delta 效果等級"""
    delta = abs(delta)
    if delta < 0.147: return "Negligible"
    if delta < 0.33: return "Small"
    if delta < 0.474: return "Medium"
    return "Large"

