def fix_broken_tokens(token_str, protect_list):
    """
    關鍵字修復函式：將被 CKIP 錯誤切分的領域關鍵字重新黏合。
    """
    fixed_str = token_str
    for word in protect_list:
        if len(word) < 2:
            continue

        # 效能優化：先確認字串首字是否存在，再執行正規表達式替換
        if word[0] in fixed_str:
            pattern = r"\s*".join([re.escape(char) for char in word])
            fixed_str = re.sub(pattern, word, fixed_str, flags=re.IGNORECASE)

    return fixed_str

