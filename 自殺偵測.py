    feature_rows = []

    for idx, row in tqdm(df.iterrows(), total=len(df), desc="特徵運算進度"):
        tokens = row['ckip_tokens'].split()
        tags = row['pos_tags'].split()
        doc_len = len(tokens) if len(tokens) > 0 else 1

        abs_count = sum(1 for t in tokens if t in ABSOLUTE_WORDS)
