def train_and_evaluate_model(X_tr, y_tr, X_te, y_te, model_name, max_feat='sqrt'):
    """封裝 5-Fold 交叉驗證與獨立測試集評估"""

    rf_model = RandomForestClassifier(
        n_estimators=300,
        max_depth=15,                   # 限制深度防止過度擬合假樣本
        min_samples_split=5,
        class_weight='balanced_subsample',
        max_features=max_feat,
        random_state=42,
        n_jobs=-1
    )

    # 執行 5-Fold 交叉驗證取得訓練集穩定性分數
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    cv_results = cross_validate(
        rf_model, X_tr, y_tr, cv=skf,
        scoring=['accuracy', 'f1_weighted'], return_train_score=False
    )

    print(f"\n======= {model_name} =======")
    print(f"[訓練集 5-Fold 驗證] 平均 Accuracy: {np.mean(cv_results['test_accuracy']):.4f} (+/- {np.std(cv_results['test_accuracy']):.4f})")
    print(f"[訓練集 5-Fold 驗證] 平均 Weighted F1: {np.mean(cv_results['test_f1_weighted']):.4f}")

    # 在獨立測試集上進行最終訓練與預測
    rf_model.fit(X_tr, y_tr)
    y_pred = rf_model.predict(X_te)

    print(f"\n[獨立測試集最終報告]")
    print(classification_report(y_te, y_pred, target_names=['Low Risk (0)', 'High Risk (1)']))

    return rf_model, y_pred

